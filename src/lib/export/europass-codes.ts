function lookup(table: Record<string, string>, name: string): string | null {
  return table[S.toLowerCase(S.trim(name))] ?? null;
}

export function languageCode(name: string): string | null {
  return lookup(LANGUAGE_CODES, name);
}

export function countryCode(name: string): string | null {
  return lookup(COUNTRY_CODES, name);
}
